export function productBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function productById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

/** Courses, videos and packages have a lesson player; PDFs/e-books are downloads. */
export function isLearnable(p: Product): boolean {
  return p.type === "course" || p.type === "video" || p.type === "package";
}

export function productHref(p: Product): string {
  return isLearnable(p) ? `/courses/${p.slug}` : `/store/${p.slug}`;
}
