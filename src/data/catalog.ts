function curriculum(spec: [string, [string, string, boolean?][]][]): CourseSection[] {
  return spec.map(([title, lessons], si) => ({
    id: `s${si + 1}`,
    title,
    lessons: lessons.map(([t, d, free], li) => ({ id: `s${si + 1}-l${li + 1}`, title: t, duration: d, free })),
  }));
}

